def setup(doc: Document) -> None:
    section = doc.sections[0]
    section.top_margin = Cm(1.8)
    section.bottom_margin = Cm(1.8)
    section.left_margin = Cm(2)
    section.right_margin = Cm(2)
    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(11)


def h(doc: Document, text: str, level: int) -> None:
    doc.add_heading(text, level=level)


def p(doc: Document, text: str, bold: bool = False) -> None:
    para = doc.add_paragraph()
    run = para.add_run(text)
    run.bold = bold
    run.font.size = Pt(11)


def fn(doc: Document, name: str, importance: str, what: str, blocks: list[str]) -> None:
    para = doc.add_paragraph()
    r = para.add_run(name)
    r.bold = True
    r.font.size = Pt(12)
    r.font.color.rgb = RGBColor(0x0B, 0x3D, 0x2E) if importance == "важная" else RGBColor(0x3D, 0x52, 0x48)
    tag = doc.add_paragraph()
    tr = tag.add_run("Важность: " + importance)
    tr.italic = True
    tr.font.size = Pt(10)
    p(doc, what)
    if blocks:
        p(doc, "Блоки работы:", bold=True)
        for i, block in enumerate(blocks, 1):
            doc.add_paragraph(f"{i}. {block}", style="List Number")


